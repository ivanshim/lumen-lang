def _rotate(word, count):
    return ((word >> count) | (word << (64 - count))) & _MASK

def digest(data):
    data = bytes(data)
    length = len(data) * 8
    padded = data + b'\x80'
    padded += b'\x00' * ((240 - len(padded) % 128) % 128)
    padded += length.to_bytes(16, 'big')
    state = list(_INITIAL)
    for start in range(0, len(padded), 128):
        words = [int.from_bytes(padded[start+i:start+i+8], 'big') for i in range(0, 128, 8)]
        for i in range(16, 80):
            x, y = words[i-15], words[i-2]
            s0 = _rotate(x, 1) ^ _rotate(x, 8) ^ (x >> 7)
            s1 = _rotate(y, 19) ^ _rotate(y, 61) ^ (y >> 6)
            words.append((words[i-16] + s0 + words[i-7] + s1) & _MASK)
        a, b, c, d, e, f, g, h = state
        for i in range(80):
            upper = _rotate(e, 14) ^ _rotate(e, 18) ^ _rotate(e, 41)
            choice = (e & f) ^ ((~e) & g)
            first = (h + upper + choice + _ROUND[i] + words[i]) & _MASK
            lower = _rotate(a, 28) ^ _rotate(a, 34) ^ _rotate(a, 39)
            majority = (a & b) ^ (a & c) ^ (b & c)
            second = (lower + majority) & _MASK
            a, b, c, d, e, f, g, h = (first + second) & _MASK, a, b, c, (d + first) & _MASK, e, f, g
        state = [(old + new) & _MASK for old, new in zip(state, (a,b,c,d,e,f,g,h))]
    return b''.join(word.to_bytes(8, 'big') for word in state)
